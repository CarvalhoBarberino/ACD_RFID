	D3_NUMSEQ 
FROM 
	SD3990  
WHERE 
	D3_FILIAL = '01' 
	AND D3_OP = '000028' 
	AND D3_COD = '000001' 
	AND D3_LOCAL = '01' 
	AND D3_CF = 'PR0' 

SELECT 
	C9_FILIAL, 
	C9_PEDIDO, 
	C9_CLIENTE, 
	C9_LOJA, 
	C5_FECENT AS DTENTREGA, 
	C9_ITEM, 
	C9_SEQUEN, 
	C9_PRODUTO, 
	B1_DESC, 
	C9_LOCAL, 
	C9_LOTECTL, 
	C9_NUMSERI, 
	C9_QTDLIB, 
	C9_PEDIDO + C9_ITEM + C9_SEQUEN AS REC, 
	'' AS SEL_OK 
FROM 
	SC9990 C9 
	INNER JOIN 
		SC5990 C5 
		ON C9_FILIAL = C5_FILIAL 
		AND C9_PEDIDO = C5_NUM 
		AND C5.D_E_L_E_T_ = '' 
	INNER JOIN 
		SB1990 B1 
		ON C9_FILIAL = B1_FILIAL 
		AND B1_COD = C9_PRODUTO 
		AND B1.D_E_L_E_T_ = '' 
WHERE 
	C9_PEDIDO BETWEEN '' AND 'ZZZZZ' 
	AND C9_CLIENTE BETWEEN '' AND 'ZZZZZZ' 
	AND C9_LOJA BETWEEN '      ' AND 'ZZZZZZ' 
	AND C5_FECENT BETWEEN '        ' AND 'ZZZZZZZZ' 
	AND C9_PRODUTO BETWEEN '      ' AND 'ZZZZZZ' 
	AND C9_BLEST = '' 
	AND C9_BLCRED = '' 
	AND C9.D_E_L_E_T_ = '' 
ORDER BY 
	C9_PEDIDO, 
	C9_ITEM, 
	C9_SEQUEN; 

